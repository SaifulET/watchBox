const inferAuth = (path: string): string => {
  if (path.includes("/auth/login") || path.includes("/auth/register") || path.includes("/auth/refresh") || path.includes("forgot-password") || path.includes("reset-password") || path.includes("verify-email") || path.includes("verify-reset-code") || path.includes("mfa/challenge")) {
    return "Public";
  }
  if (path.startsWith("/api/v1/admin")) {
    return "Admin";
  }
  return "Customer";
};

const inferPermission = (path: string): string => {
  if (!path.startsWith("/api/v1/admin") || path.startsWith("/api/v1/admin/auth")) {
    return "-";
  }
  const [, , , , moduleName = "admin"] = path.split("/");
  return `admin:${moduleName}`;
};

const endpoint = (method: RequiredApiEndpoint["method"], path: string): RequiredApiEndpoint => {
  const key = `${method} ${path}`;
  return {
    method,
    path,
    auth: inferAuth(path),
    permission: inferPermission(path),
    status: verifiedRoutes.has(key) ? "VERIFIED" : "IMPLEMENTED"
  };
};

